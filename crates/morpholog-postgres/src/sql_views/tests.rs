use super::*;
use morpholog_core::{ArgDecl, PredicateDecl};
use morpholog_surface::parse_program;

fn decl(name: &str, args: &[(&str, PredicateArgKind)]) -> PredicateDecl {
    PredicateDecl {
        name: name.into(),
        args: args
            .iter()
            .map(|(n, k)| ArgDecl {
                name: (*n).to_string(),
                kind: k.clone(),
            })
            .collect(),
        disciplines: Vec::new(),
    }
}

fn render_ok(src: &str) -> RenderedViews {
    let program = parse_program(src).expect("fixture parses");
    let validated = program.validated().expect("fixture validates");
    render_views(
        &validated,
        "morpholog_views",
        "sha256:testhash",
        DerivedSource::Cache,
    )
    .expect("renders")
}

fn refusals(src: &str, schema: &str) -> Vec<ViewRefusal> {
    let program = parse_program(src).expect("fixture parses");
    let validated = program.validated().expect("fixture validates");
    render_views(&validated, schema, "sha256:testhash", DerivedSource::Cache).expect_err("refuses")
}

