/// The description is read off the column lists the SQL is rendered
/// from: metadata columns first with the source's types, then the
/// fields in declaration order with the kind as `schema` spells it and
/// the type the view casts to; the identity is each `unique by` clause
/// for a base predicate and the key fields for a derived one.
#[test]
fn the_description_follows_the_rendered_columns() {
    let rendered = render_ok(
        "program described
predicate Position(book: Subject, instrument: Subject, qty: Decimal[MWh], since: Date, at: Timestamp, held: Duration, open: Bool, tags: Collection, raw: Any)
    unique by (book, instrument)
    unique by (at)
predicate Note(id: Subject)
predicate Exposure(book: Subject, total: Decimal[MWh])
derived Exposure(book):
    over Position(book, _, q, _, _, _, _, _, _)
    value total = sum(q | Position(book, _, q, _, _, _, _, _, _))
",
    );
    let surface = &rendered.surface;
    assert_eq!(surface.format, VIEW_SURFACE_FORMAT);
    assert_eq!(surface.programme, "described");
    assert_eq!(surface.model_hash, "sha256:testhash");
    assert_eq!(surface.schema, "morpholog_views");
    assert_eq!(surface.catalog, "_morpholog_catalog");
    assert_eq!(surface.seal_table, "_morpholog_view_defs");
    let names: Vec<(&str, &str)> = surface
        .views
        .iter()
        .map(|v| (v.view.as_str(), v.kind.as_str()))
        .collect();
    assert_eq!(
        names,
        [
            ("position", "base"),
            ("note", "base"),
            ("exposure", "derived")
        ]
    );

    let position = &surface.views[0];
    assert_eq!(position.predicate, "Position");
    assert_eq!(
        position.identity,
        vec![
            vec!["book".to_string(), "instrument".to_string()],
            vec!["at".to_string()]
        ]
    );
    type Shown = (String, String, Option<String>, String, Option<usize>);
    let shown: Vec<Shown> = position
        .columns
        .iter()
        .map(|c| {
            (
                c.name.clone(),
                c.role.clone(),
                c.kind.clone(),
                c.sql_type.clone(),
                c.position,
            )
        })
        .collect();
    let meta = |name: &str, ty: &str| {
        (
            name.to_string(),
            "metadata".to_string(),
            None,
            ty.to_string(),
            None,
        )
    };
    let field = |name: &str, kind: &str, ty: &str, i: usize| {
        (
            name.to_string(),
            "field".to_string(),
            Some(kind.to_string()),
            ty.to_string(),
            Some(i),
        )
    };
    assert_eq!(
        shown,
        vec![
            meta("_morpholog_asserted_in", "uuid"),
            meta("_morpholog_asserted_at", "timestamptz"),
            meta("_morpholog_arguments", "jsonb"),
            field("book", "Subject", "text", 0),
            field("instrument", "Subject", "text", 1),
            field("qty", "Decimal[MWh]", "numeric", 2),
            field("since", "Date", "date", 3),
            field("at", "Timestamp", "timestamptz", 4),
            field("held", "Duration", "interval", 5),
            field("open", "Bool", "boolean", 6),
            field("tags", "Collection", "jsonb", 7),
            field("raw", "Any", "jsonb", 8),
        ]
    );
    assert!(
        surface.views[1].identity.is_empty(),
        "no clause, no identity"
    );

    let exposure = &surface.views[2];
    assert_eq!(exposure.identity, vec![vec!["book".to_string()]]);
    let meta_names: Vec<&str> = exposure
        .columns
        .iter()
        .filter(|c| c.role == "metadata")
        .map(|c| c.name.as_str())
        .collect();
    assert_eq!(
        meta_names,
        [
            "_morpholog_refreshed_at",
            "_morpholog_model_hash",
            "_morpholog_source_snapshot_transition_id",
            "_morpholog_source_snapshot_committed_at",
            "_morpholog_arguments"
        ]
    );
    // Every SQL column is described, in the SQL's order.
    for view in &surface.views {
        let block = rendered
            .sql
            .split("CREATE OR REPLACE VIEW")
            .find(|b| b.contains(&format!("\"{}\" AS", view.view)))
            .unwrap();
        let aliases: Vec<&str> = block
            .lines()
            .filter_map(|l| {
                l.trim_end_matches(',')
                    .rsplit_once(" AS \"")
                    .map(|(_, a)| a.trim_end_matches('"'))
            })
            .collect();
        let described: Vec<&str> = view.columns.iter().map(|c| c.name.as_str()).collect();
        assert_eq!(aliases, described, "{}", view.view);
    }
}

/// Applied to PostgreSQL, every view has the described columns, in the
/// described order, with the described types: the agreement a consumer
/// can check itself from `information_schema.columns`.
#[tokio::test]
async fn the_applied_views_have_the_described_columns() {
    let pool = crate::compiled_differential::test_pool().await;
    crate::testing::reset_database(&pool).await.unwrap();
    for program in morpholog_examples::all_programs() {
        let validated = program.validated().unwrap();
        let hash = format!("sha256:{}", "0".repeat(64));
        let schema = "described_views";
        let Ok(rendered) = render_views(&validated, schema, &hash, DerivedSource::Cache) else {
            continue;
        };
        // Safe: the schema name is this test's constant.
        sqlx::raw_sql(sqlx::AssertSqlSafe(format!(
            "DROP SCHEMA IF EXISTS {schema} CASCADE"
        )))
        .execute(&pool)
        .await
        .unwrap();
        sqlx::raw_sql(sqlx::AssertSqlSafe(rendered.sql.clone()))
            .execute(&pool)
            .await
            .unwrap_or_else(|e| panic!("{}: applying the views: {e}", program.name));
        for view in &rendered.surface.views {
            let rows: Vec<(String, String)> = sqlx::query_as(
                "SELECT column_name::text, udt_name::text FROM information_schema.columns
                 WHERE table_schema = $1 AND table_name = $2 ORDER BY ordinal_position",
            )
            .bind(schema)
            .bind(&view.view)
            .fetch_all(&pool)
            .await
            .unwrap();
            let described: Vec<(String, String)> = view
                .columns
                .iter()
                .map(|c| (c.name.clone(), c.sql_type.clone()))
                .collect();
            assert_eq!(rows, described, "{}.{}", program.name, view.view);
        }
    }
}

const LIVE_SOURCE: &str = "program live_source
predicate Part(part: Subject)
predicate StockItem(item: Subject, part: Subject, quantity: Decimal)
predicate SalesAllocation(allocation: Subject, item: Subject, quantity: Decimal)
predicate Allocated(item: Subject, quantity: Decimal)
predicate PartAllocated(part: Subject, quantity: Decimal)
define allocated_to(allocation, item, quantity):
    SalesAllocation(allocation, item, quantity)
derived Allocated(item):
    over StockItem(item: item, ..)
    value quantity = sum(q | SalesAllocation(_, item, q))
derived PartAllocated(part):
    over Part(part: part)
    value quantity = sum(q | SalesAllocation(_, i, q) and StockItem(i, part, _))
";

/// Under `Live`, a derived view is computed from its definition: the
/// distinct keys of its domain, each value a sum as a lateral, the model
/// hash and the error column first; the description says `live`, the
/// cache's provenance columns are gone, and the base views are untouched.
#[test]
fn live_derived_views_are_computed_from_their_definitions() {
    let program = parse_program(LIVE_SOURCE).unwrap();
    let validated = program.validated().unwrap();
    let cached = render_views(
        &validated,
        "morpholog_views",
        "sha256:testhash",
        DerivedSource::Cache,
    )
    .unwrap();
    let live = render_views(
        &validated,
        "morpholog_views",
        "sha256:testhash",
        DerivedSource::Live,
    )
    .unwrap();
    assert_eq!(live.derived_view_count, 2);
    let block = live
        .sql
        .split("CREATE OR REPLACE VIEW")
        .find(|b| b.contains("\"allocated\" AS"))
        .unwrap();
    assert!(
        block.contains("WITH live AS ("),
        "read-only wrapper: {block}"
    );
    assert!(block.contains(
        "SELECT DISTINCT ON (morpholog.claim_digest(morpholog.value_key_v1(t0.arguments -> 0)))"
    ));
    assert!(block.contains("LATERAL (SELECT COALESCE(sum("));
    assert!(block.contains("AS \"_morpholog_error\""));
    assert!(
        !block.contains("morpholog_read."),
        "a live view never reads the cache"
    );
    let described: Vec<(&str, Option<&str>, Vec<&str>)> = live
        .surface
        .views
        .iter()
        .filter(|v| v.kind == "derived")
        .map(|v| {
            (
                v.view.as_str(),
                v.source.as_deref(),
                v.columns.iter().map(|c| c.name.as_str()).collect(),
            )
        })
        .collect();
    assert_eq!(
        described,
        vec![
            (
                "allocated",
                Some("live"),
                vec![
                    "_morpholog_model_hash",
                    "_morpholog_error",
                    "item",
                    "quantity"
                ]
            ),
            (
                "part_allocated",
                Some("live"),
                vec![
                    "_morpholog_model_hash",
                    "_morpholog_error",
                    "part",
                    "quantity"
                ]
            ),
        ]
    );
    let cached_derived: Vec<Option<&str>> = cached
        .surface
        .views
        .iter()
        .filter(|v| v.kind == "derived")
        .map(|v| v.source.as_deref())
        .collect();
    assert_eq!(cached_derived, vec![Some("cache"), Some("cache")]);
    assert!(
        cached
            .surface
            .views
            .iter()
            .filter(|v| v.kind == "base")
            .all(|v| v.source.is_none())
    );
    // The base views' SQL is the same under both sources.
    let base_sql = |sql: &str| sql.split("-- View for derived").next().unwrap().to_string();
    assert_eq!(base_sql(&cached.sql), base_sql(&live.sql));
}

/// A definition the renderer cannot express refuses the live run by the
/// derived claim's name, with the renderer's reason, and writes nothing;
/// the same programme renders from the cache as before.
#[test]
fn a_live_derived_claim_outside_the_fragment_refuses_by_name() {
    let source = format!(
        "{LIVE_SOURCE}predicate OnHand(item: Subject, quantity: Decimal)
derived OnHand(item):
    over StockItem(item: item, ..)
    value quantity = value StockItem(item: item, quantity: _, ..)
"
    );
    let program = parse_program(&source).unwrap();
    let validated = program.validated().unwrap();
    let refused = render_views(
        &validated,
        "morpholog_views",
        "sha256:testhash",
        DerivedSource::Live,
    )
    .expect_err("a value lookup is outside the fragment");
    assert_eq!(refused.len(), 1);
    assert_eq!(
        refused[0].to_string(),
        "derived `OnHand` cannot be read live: `value lookup` is outside the compiled fragment; keep `--derived cache` or respell it"
    );
    assert!(
        render_views(
            &validated,
            "morpholog_views",
            "sha256:testhash",
            DerivedSource::Cache
        )
        .is_ok()
    );
}

/// A definition call that binds under a sum renders, in a live view
/// only, as the distinct projection of its body's branches: the kernel
/// counts each distinct projection once, and so does the SQL.
#[test]
fn a_binding_call_under_a_sum_renders_live_as_a_distinct_projection() {
    let source = format!(
        "{LIVE_SOURCE}predicate Counted(item: Subject, quantity: Decimal)
derived Counted(item):
    over StockItem(item: item, ..)
    value quantity = sum(q | allocated_to(a, item, q))
"
    );
    let program = parse_program(&source).unwrap();
    let validated = program.validated().unwrap();
    let live = render_views(
        &validated,
        "morpholog_views",
        "sha256:testhash",
        DerivedSource::Live,
    )
    .expect("a binding call renders live");
    let block = live
        .sql
        .split("CREATE OR REPLACE VIEW")
        .find(|b| b.contains("\"counted\" AS"))
        .unwrap();
    assert!(block.contains("LATERAL (SELECT DISTINCT ON ("), "{block}");
    assert!(block.contains("jsonb_build_array("), "{block}");
    assert!(
        !block.contains("_call:"),
        "the pseudo-predicate never reaches the SQL: {block}"
    );
}
